// Keep anonymous translation restricted to shipped public interface copy.
import fs from 'node:fs';
import ts from 'typescript';
const texts=new Set();
for(const file of ['components/landing/landing-page.tsx','components/auth/login-form.tsx','components/learning/translation.tsx','lib/coach-preferences.ts']){
 const source=fs.readFileSync(file,'utf8'),sf=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true);
 function visit(n){if(ts.isJsxText(n)){const text=n.text.replace(/\s+/g,' ').trim();if(text)texts.add(text)}else if(ts.isStringLiteralLike(n)&&/\p{L}/u.test(n.text))texts.add(n.text);ts.forEachChild(n,visit)}visit(sf);
}
fs.writeFileSync('lib/public-ui-texts.ts','// Generated by scripts/update-public-ui-texts.mjs. No account or user data.\nexport const publicUiTexts:string[]='+JSON.stringify([...texts].sort(),null,2)+';\n');
